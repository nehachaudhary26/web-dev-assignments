// Assignment 43: runs the validation test matrix and writes TEST_MATRIX.md (run: node matrix.js)
const fs = require("fs");
const path = require("path");
const { validateContact } = require("../a42-contact-form/validation");
const good = { name: "Aish Kalra", email: "aish@example.com", phone: "9876543210", subject: "General", message: "Hello, this is a test message.", agree: true };
const T = (id, field, scenario, override, expected, check) => ({ id, field, scenario, input: { ...good, ...override }, expected, check });
const cases = [
  T("V01", "all", "Fully valid submission", {}, "valid", (r) => r.valid),
  T("V02", "name", "Empty name", { name: "" }, "error: Name is required.", (r) => r.errors.name === "Name is required."),
  T("V03", "name", "1-character name (below minimum)", { name: "A" }, "error: at least 2 characters", (r) => /at least 2/.test(r.errors.name)),
  T("V04", "name", "HTML tags are stripped", { name: "<b>Aish</b>" }, "valid, cleaned name 'Aish'", (r) => r.valid && r.data.name === "Aish"),
  T("V05", "name", "51-character name (above maximum)", { name: "a".repeat(51) }, "error: 50 characters or fewer", (r) => /50 characters/.test(r.errors.name)),
  T("V06", "email", "Missing @", { email: "aish.example.com" }, "error: valid email", (r) => /valid email/.test(r.errors.email)),
  T("V07", "email", "Uppercase and spaces are normalised", { email: "  AISH@Example.COM " }, "valid, 'aish@example.com'", (r) => r.valid && r.data.email === "aish@example.com"),
  T("V08", "phone", "Phone left empty (optional)", { phone: "" }, "valid", (r) => r.valid),
  T("V09", "phone", "Spaces and dashes accepted", { phone: "98765-43210" }, "valid, '9876543210'", (r) => r.valid && r.data.phone === "9876543210"),
  T("V10", "phone", "Too short", { phone: "12345" }, "error: valid 10-digit", (r) => /10-digit/.test(r.errors.phone)),
  T("V11", "subject", "No subject chosen", { subject: "" }, "error: choose a subject", (r) => /choose a subject/i.test(r.errors.subject)),
  T("V12", "subject", "Subject not in list", { subject: "Spam" }, "error: from the list", (r) => /from the list/.test(r.errors.subject)),
  T("V13", "message", "9 characters (boundary - 1)", { message: "123456789" }, "error: at least 10", (r) => /at least 10/.test(r.errors.message)),
  T("V14", "message", "10 characters (boundary)", { message: "1234567890" }, "valid", (r) => r.valid),
  T("V15", "message", "501 characters (boundary + 1)", { message: "x".repeat(501) }, "error: 500 characters or fewer", (r) => /500 characters/.test(r.errors.message)),
  T("V16", "message", "Only HTML tags", { message: "<b></b><i></i>" }, "error: Message is required.", (r) => r.errors.message === "Message is required."),
  T("V17", "agree", "Checkbox not ticked", { agree: false }, "error: must agree", (r) => /must agree/.test(r.errors.agree)),
  T("V18", "all", "Everything empty", { name: "", email: "", phone: "", subject: "", message: "", agree: false }, "5 errors (phone is optional)", (r) => Object.keys(r.errors).length === 5),
];
let pass = 0;
const rows = cases.map((c) => {
  const r = validateContact(c.input);
  const ok = c.check(r); if (ok) pass++;
  const actual = r.valid ? "valid" : "errors: " + Object.keys(r.errors).join(", ");
  return `| ${c.id} | ${c.field} | ${c.scenario} | ${c.expected} | ${actual} | ${ok ? "Pass" : "FAIL"} |`;
});
const md = `# Assignment 43: Validation Test Matrix (Contact Form)

Generated by \`node matrix.js\` against \`../a42-contact-form/validation.js\`.

| ID | Field | Scenario | Expected | Actual | Result |
|----|-------|----------|----------|--------|--------|
${rows.join("\n")}

**${pass}/${cases.length} passed.**

## Manual browser checks (tick after testing)
- [ ] Errors appear under each invalid field and the first invalid field gets focus
- [ ] Fields with errors are outlined in red (\`aria-invalid\`)
- [ ] A screen reader or Tab key can reach every field, and each field has a label
- [ ] Valid submit shows the summary and clears the form
- [ ] Typing \`<script>alert(1)</script>\` in Message shows plain text (or nothing) and runs nothing
- [ ] Layout works at 360px width
`;
fs.writeFileSync(path.join(__dirname, "TEST_MATRIX.md"), md);
console.log(`${pass}/${cases.length} passed - TEST_MATRIX.md written`);
process.exit(pass === cases.length ? 0 : 1);
